/** Joins lines and guarantees exactly one trailing newline. */
export function lines(parts: (string | false | undefined | null)[]): string {
  return parts.filter((p) => p !== false && p !== undefined && p !== null).join("\n").replace(/\n*$/, "\n");
}

export function lowerFirst(s: string): string {
  return s ? s[0].toLowerCase() + s.slice(1) : s;
}

/** First example value for a parameter: from examples, then schema examples/default/enum. */
export function exampleValue(
  name: string,
  schema: { examples?: unknown[]; default?: unknown; enum?: string[] },
  examples: { arguments: Record<string, unknown> }[],
): unknown {
  for (const ex of examples) if (ex.arguments[name] !== undefined) return ex.arguments[name];
  if (schema.examples?.length) return schema.examples[0];
  if (schema.default !== undefined) return schema.default;
  if (schema.enum?.length) return schema.enum[0];
  return undefined;
}

/** Fills {param} placeholders in a confirmation prompt. */
export function fillTemplate(template: string, render: (name: string) => string): string {
  return template.replace(/\{([^}]+)\}/g, (_, name: string) => render(name));
}
